package com.github.damontecres.wholphin.jellytip.channels

import org.json.JSONObject
import kotlin.math.floor

/*
 * My Channels (web parity, round 3 item 10): a straight port of web lib/channels.ts, lib/personalChannels.ts and
 * lib/tasteProfile.ts (origin/jellytip-web 0e7e7787). A channel is a seeded-shuffle lineup laid back to back from a fixed
 * epoch, so "what's on now" is a function of the clock alone: the TV and the web show the same item at the same offset.
 * Every number here (hash, PRNG, weighted keys) must match the web bit for bit; ChannelsTest checks it against vectors
 * generated by running the web code under node.
 */

const val TICKS_PER_SECOND = 10_000_000L

/** 2026-01-05 00:00 UTC, the origin of every channel's timeline. */
const val EPOCH_MS = 1_767_571_200_000L
const val MIN_ITEMS = 3
const val TUNE_MIN_LEFT_S = 15

enum class ChanType { MOVIE, EPISODE }

enum class Personal { FOR_YOU, GENRE, SHOWS }

