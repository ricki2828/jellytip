/** The slice of an item a channel keeps. Library ids are dashless 32-hex; IPTV ids are pid:m:sid / pid:e:eid. */
data class ChanItem(
    val id: String,
    val name: String,
    val type: String? = null,
    val seriesName: String? = null,
    val season: Int? = null,
    val episode: Int? = null,
    val seriesId: String? = null,
    val year: Int? = null,
    val runTimeTicks: Long? = null,
    val tmdb: String? = null,
    val seriesTmdb: String? = null,
    /** IPTV only: https TMDB art. */
    val art: String? = null,
    val genres: List<String>? = null,
    /** Taste fit 0..1 (0.5 = no opinion); null without a profile. */
    val aff: Double? = null,
)

data class Slot(
    val item: ChanItem,
    val startMs: Long,
    val endMs: Long,
)

data class Sched(
    val slots: List<Slot>,
    val offsetS: Long,
    val progress: Double,
)

data class Target(
    val id: String,
    val startS: Long,
    val thenId: String?,
    val title: String,
    /** IPTV episodes: the series id the IPTV player needs. */
    val seriesId: String? = null,
)

object Channels {
    private val VOD_ID_RE = Regex("^[A-Za-z0-9_-]{1,40}:[ms]:[A-Za-z0-9_.-]{1,64}$")
    private val EPISODE_ID_RE = Regex("^[A-Za-z0-9_-]{1,40}:e:[A-Za-z0-9_.-]{1,64}$")
    private val TMDB_ART = Regex("^https://image\\.tmdb\\.org/")

    const val IPTV_MIN_S = 40 * 60
    const val IPTV_MAX_S = 300 * 60
    const val IPTV_CAP = 100
    const val IPTV_EP_MIN_S = 5 * 60
    const val IPTV_EP_MAX_S = 120 * 60
    const val IPTV_EP_CAP = 200
    const val BLOCK_MIN = 2
    const val BLOCK_MAX = 4
    const val CHAIN_MAX = 3
    const val CHAIN_WINDOW_MS = 120_000L

    fun isIptvEpisodeId(id: String) = EPISODE_ID_RE.matches(id)

    fun isIptvId(id: String) = VOD_ID_RE.matches(id) || EPISODE_ID_RE.matches(id)

    fun channelById(
        id: String?,
        personal: List<ChannelDef> = emptyList(),
    ): ChannelDef? = CHANNELS.firstOrNull { it.id == id } ?: personal.firstOrNull { it.id == id }

    // ---------- seed ----------

    /** FNV-1a over UTF-16 code units, 32 bit unsigned (as JS `>>> 0`). */
    fun hashString(s: String): Long {
        var h = 0x811c9dc5.toInt()
        for (ch in s) {
            h = h xor ch.code
            h *= 0x01000193
        }
        return h.toLong() and 0xFFFFFFFFL
    }

    /** mulberry32: [0,1), identical to the web's. */
    fun rng(seed: Long): () -> Double {
        var a = seed.toInt()
        return {
            a += 0x6d2b79f5
            var t = a
            t = (t xor (t ushr 15)) * (t or 1)
            t = t xor (t + (t xor (t ushr 7)) * (t or 61))
            ((t xor (t ushr 14)).toLong() and 0xFFFFFFFFL) / 4294967296.0
        }
    }

    fun seedFor(
        channelId: String,
        cycle: Long,
    ): Long = hashString("$channelId|c$cycle")

    // ---------- pool ----------

    fun seconds(it: ChanItem): Long = (it.runTimeTicks ?: 0L).let { t -> if (t > 0) t / TICKS_PER_SECOND else 0L }

    fun playable(
        items: List<ChanItem>,
        def: ChannelDef? = null,
    ): List<ChanItem> {
        val seen = HashSet<String>()
        val out = ArrayList<ChanItem>()
        for (it in items) {
            if (it.id.isEmpty() || it.id in seen) continue
            val s = seconds(it)
            if (s < 60) continue
            if (def?.maxMinutes != null && def.maxMinutes > 0 && s > def.maxMinutes * 60L) continue
            if (def?.minMinutes != null && def.minMinutes > 0 && s < def.minMinutes * 60L) continue
            seen += it.id
            out += it
        }
        return out
    }

    fun channelViable(
        items: List<ChanItem>,
        def: ChannelDef? = null,
    ) = playable(items, def).size >= MIN_ITEMS

    fun affinityWeight(a: Double?): Double = if (a == null || !a.isFinite()) 1.0 else StrictMath.pow(4.0, a.coerceIn(0.0, 1.0) * 2 - 1)

    private fun wkey(
        h: Long,
        w: Double,
    ): Double = -StrictMath.log((h + 1) / 4294967297.0) / w

    fun meanAff(items: List<ChanItem>): Double? {
        val a = items.mapNotNull { it.aff }
        return if (a.isEmpty()) null else a.sum() / a.size
    }

    private val byKeyThenId = Comparator<Pair<Double, ChanItem>> { p, q -> p.first.compareTo(q.first).takeIf { it != 0 } ?: p.second.id.compareTo(q.second.id) }

    fun sample(
        items: List<ChanItem>,
        cap: Int,
        salt: String = "pool",
    ): List<ChanItem> {
        if (items.size <= cap) return items
        val weighted = items.any { it.aff != null }
        return items
            .map { x -> (if (weighted) wkey(hashString("$salt|${x.id}"), affinityWeight(x.aff)) else hashString("$salt|${x.id}").toDouble()) to x }
            .sortedWith(byKeyThenId)
            .take(cap)
            .map { it.second }
    }

    fun sampleByGroup(
        items: List<ChanItem>,
        group: (ChanItem) -> String?,
        perGroup: Int,
        cap: Int,
        salt: String = "pool",
    ): List<ChanItem> {
        val by = LinkedHashMap<String, MutableList<ChanItem>>()
        for (x in items) group(x)?.let { by.getOrPut(it) { ArrayList() } += x }
        return sample(by.values.flatMap { sample(it, perGroup, salt) }, cap, salt)
    }

    fun poolOf(
        items: List<ChanItem>,
        def: ChannelDef? = null,
    ): List<ChanItem> = playable(items, def).sortedWith { x, y -> x.id.compareTo(y.id) }

    val byEpisodeOrder =
        Comparator<ChanItem> { a, b ->
            ((a.season ?: 0) - (b.season ?: 0)).takeIf { it != 0 }
                ?: ((a.episode ?: 0) - (b.episode ?: 0)).takeIf { it != 0 }
                ?: a.id.compareTo(b.id)
        }

    /** One pass of the channel: the pool in a seeded shuffle; series kept in blocks of 2-4 consecutive episodes. */
    fun lineup(
        pool: List<ChanItem>,
        channelId: String,
        cycle: Long,
    ): List<ChanItem> {
        val r = rng(seedFor(channelId, cycle))
        var blocks: MutableList<List<ChanItem>>
        if (pool.any { it.seriesId != null }) {
            val by = LinkedHashMap<String, MutableList<ChanItem>>()
            blocks = ArrayList()
            for (x in pool) {
                if (x.seriesId == null) blocks += listOf(x) else by.getOrPut(x.seriesId) { ArrayList() } += x
            }
            for (sid in by.keys.sorted()) {
                val eps = by.getValue(sid).sortedWith(byEpisodeOrder)
                var i = 0
                while (i < eps.size) {
                    var n = BLOCK_MIN + floor(r() * (BLOCK_MAX - BLOCK_MIN + 1)).toInt()
                    if (eps.size - i - n == 1) n++
                    if (n > BLOCK_MAX + 1) n = BLOCK_MAX + 1
                    blocks += eps.subList(i, minOf(eps.size, i + n))
                    i += n
                }
            }
        } else {
            blocks = pool.map { listOf(it) }.toMutableList()
        }
        if (pool.any { it.aff != null }) {
            blocks = blocks.map { b -> (-StrictMath.log(1 - r()) / affinityWeight(meanAff(b))) to b }.sortedBy { it.first }.map { it.second }.toMutableList()
        } else {
            for (i in blocks.size - 1 downTo 1) {
                val j = floor(r() * (i + 1)).toInt()
                val t = blocks[i]
                blocks[i] = blocks[j]
                blocks[j] = t
            }
        }
        fun sid(b: List<ChanItem>?) = b?.get(0)?.seriesId
        for (i in 1 until blocks.size) {
            if (sid(blocks[i]) == null || sid(blocks[i]) != sid(blocks[i - 1])) continue
            val nextSid = sid(blocks.getOrNull(i + 1) ?: blocks[i])
            var k = blocks.indices.firstOrNull { k -> k > i && sid(blocks[k]) != sid(blocks[i - 1]) && sid(blocks[k]) != nextSid } ?: -1
            if (k < 0) k = blocks.indices.firstOrNull { k2 -> k2 > i && sid(blocks[k2]) != sid(blocks[i - 1]) } ?: -1
            if (k > i) {
                val t = blocks[i]
                blocks[i] = blocks[k]
                blocks[k] = t
            }
        }
        return blocks.flatten()
    }

    fun cycleSeconds(list: List<ChanItem>): Long = list.sumOf { seconds(it) }

    // ---------- schedule ----------

    /** What is on at [nowMs] and what follows ([count] slots, the current one first). [pool] must come from [poolOf]. */
    fun schedule(
        pool: List<ChanItem>,
        channelId: String,
        nowMs: Long,
        count: Int = 4,
    ): Sched {
        val total = cycleSeconds(pool)
        if (pool.isEmpty() || total <= 0) return Sched(emptyList(), 0, 0.0)
        val totalMs = total * 1000
        val sinceMs = maxOf(0L, nowMs - EPOCH_MS)
        var cycle = sinceMs / totalMs
        var posMs = sinceMs - cycle * totalMs
        var list = lineup(pool, channelId, cycle)
        var i = 0
        while (posMs >= seconds(list[i]) * 1000) {
            posMs -= seconds(list[i]) * 1000
            i++
        }
        val slots = ArrayList<Slot>()
        var t = nowMs - posMs
        repeat(count) {
            if (i >= list.size) {
                cycle++
                list = lineup(pool, channelId, cycle)
                i = 0
            }
            val item = list[i++]
            val end = t + seconds(item) * 1000
            slots += Slot(item, t, end)
            t = end
        }
        return Sched(slots, posMs / 1000, posMs.toDouble() / (seconds(slots[0].item) * 1000))
    }

    fun itemTitle(it: ChanItem): String = if (it.type == "Episode" || it.seriesName != null) (it.seriesName?.takeIf { s -> s.isNotEmpty() } ?: it.name) else it.name

    /** "S2E4 · Name" for an episode, the year for a film. */
    fun itemSub(it: ChanItem): String =
        if (it.type == "Episode" || it.seriesName != null) {
            val code = if (it.season != null && it.episode != null) "S${it.season}E${it.episode}" else ""
            listOf(code, if (it.seriesName != null) it.name else "").filter { s -> s.isNotEmpty() }.joinToString(" · ")
        } else {
            it.year?.toString() ?: ""
        }

    fun playTitle(it: ChanItem): String {
        if (!isIptvEpisodeId(it.id)) return itemTitle(it)
        val code = if (it.season != null && it.episode != null) "S${it.season} E${it.episode}" else ""
        return listOf(it.seriesName ?: "", code, it.name).filter { s -> s.isNotEmpty() }.joinToString(" · ")
    }

    private fun targetFor(
        it: ChanItem,
        startS: Long,
        then: ChanItem?,
    ) = Target(it.id, startS, then?.id, playTitle(it), if (isIptvEpisodeId(it.id)) it.seriesId else null)

    /** Where "Tune in" goes: the current item at its offset, or the next from 0 when the current one is nearly over. */
    fun tuneTarget(
        slots: List<Slot>,
        offsetS: Long,
    ): Target? {
        if (slots.isEmpty()) return null
        val cur = slots[0]
        val left = (cur.endMs - cur.startMs) / 1000.0 - offsetS
        if (left < TUNE_MIN_LEFT_S && slots.size > 1) return targetFor(slots[1].item, 0, slots.getOrNull(2)?.item)
        return targetFor(cur.item, offsetS, slots.getOrNull(1)?.item)
    }

    /** After [currentId] ended: the tune target, but never the item that just ended (a short file would loop). */
    fun chainTarget(
        slots: List<Slot>,
        offsetS: Long,
        currentId: String?,
    ): Target? {
        val t = tuneTarget(slots, offsetS)
        if (t == null || currentId == null || t.id != currentId) return t
        val nxt = slots.indexOfFirst { it.item.id != currentId }
        if (nxt < 0) return null
        return targetFor(slots[nxt].item, 0, slots.getOrNull(nxt + 1)?.item)
    }

    /** "From start": the item on now, from 0. */
    fun fromStartTarget(slots: List<Slot>): Target? = slots.firstOrNull()?.let { targetFor(it.item, 0, slots.getOrNull(1)?.item) }

    /** More than [CHAIN_MAX] automatic hops inside [CHAIN_WINDOW_MS] means something loops: stop. */
    fun chainBudget(
        stamps: List<Long>,
        nowMs: Long,
    ): Pair<Boolean, List<Long>> {
        val recent = stamps.filter { nowMs - it < CHAIN_WINDOW_MS && it <= nowMs }
        return if (recent.size >= CHAIN_MAX) false to recent else true to (recent + nowMs)
    }

    /** OK to chain on when it played a minute, or most of what was left. */
    fun playedEnough(
        playedS: Double,
        expectedLeftS: Double,
    ): Boolean = playedS >= minOf(60.0, maxOf(0.0, expectedLeftS) * 0.8)

    // ---------- library + IPTV mixing ----------

    fun yearsParam(def: ChannelDef): List<Int>? {
        val f = def.yearFrom ?: return null
        val t = def.yearTo ?: return null
        if (t < f || t - f > 100) return null
        return (f..t).toList()
    }

    fun withinYearTo(
        items: List<ChanItem>,
        def: ChannelDef,
    ): List<ChanItem> = if (def.yearTo == null) items else items.filter { it.year != null && it.year <= def.yearTo }

    fun mixItems(
        library: List<ChanItem>,
        iptv: List<ChanItem>,
        cap: Int = IPTV_CAP,
        salt: String = "iptv",
    ): List<ChanItem> {
        val have = library.mapNotNull { it.tmdb }.toSet()
        val seen = HashSet<String>()
        val extra =
            iptv.filter { i ->
                val t = i.tmdb ?: return@filter true
                if (t in have || t in seen) return@filter false
                seen += t
                true
            }
        return library + sample(extra, cap, salt)
    }

    fun mixEpisodes(
        library: List<ChanItem>,
        iptv: List<ChanItem>,
        cap: Int = IPTV_EP_CAP,
        salt: String = "iptv-ep",
    ): List<ChanItem> {
        val have = library.mapNotNull { it.seriesTmdb }.toSet()
        val bySeries = LinkedHashMap<String, MutableList<ChanItem>>()
        for (e in iptv) {
            val sid = e.seriesId ?: continue
            if (e.seriesTmdb != null && e.seriesTmdb in have) continue
            bySeries.getOrPut(sid) { ArrayList() } += e
        }
        val claimed = HashSet<String>()
        val weighted = iptv.any { it.aff != null }
        val groups =
            bySeries.entries
                .sortedBy { it.key }
                .filter { (_, eps) ->
                    val t = eps[0].seriesTmdb ?: return@filter true
                    if (t in claimed) return@filter false
                    claimed += t
                    true
                }.map { (sid, eps) ->
                    val h = hashString("$salt|$sid")
                    Triple(if (weighted) wkey(h, affinityWeight(meanAff(eps))) else h.toDouble(), sid, eps.sortedWith(byEpisodeOrder))
                }.sortedWith { p, q -> p.first.compareTo(q.first).takeIf { it != 0 } ?: p.second.compareTo(q.second) }
        val out = ArrayList<ChanItem>()
        for ((_, _, eps) in groups) {
            if (out.size + eps.size > cap) continue
            out += eps
        }
        return library + out
    }

    /** GET /v1/iptv/channel-pool → films (valid id, title, trustworthy runtime; langUnknown out) and the pending count. */
    fun iptvPoolItems(json: String?): Pair<List<ChanItem>, Int> {
        val r = runCatching { JSONObject(json ?: "") }.getOrNull() ?: return emptyList<ChanItem>() to 0
        val list = r.optJSONArray("items")
        val seen = HashSet<String>()
        val items = ArrayList<ChanItem>()
        for (k in 0 until (list?.length() ?: 0)) {
            val o = list!!.opt(k) as? JSONObject ?: continue
            val id = o.opt("id") as? String ?: ""
            val title = o.opt("title") as? String ?: ""
            val secs = (o.opt("runtime") as? Number)?.toDouble()?.takeIf { it.isFinite() }?.let { floor(it).toLong() } ?: 0L
            if (!isIptvId(id) || !id.contains(":m:") || title.isEmpty() || id in seen || o.opt("langUnknown") == true) continue
            if (secs < IPTV_MIN_S || secs > IPTV_MAX_S) continue
            seen += id
            items +=
                ChanItem(
                    id = id,
                    name = title,
                    type = "Movie",
                    year = (o.opt("year") as? Number)?.toInt(),
                    runTimeTicks = secs * TICKS_PER_SECOND,
                    tmdb = (o.opt("tmdbId") as? Number)?.toLong()?.toString(),
                    art = art(o),
                    aff = serverAff(o),
                )
        }
        return items to pending(r)
    }

    /** GET /v1/iptv/channel-pool?kind=episode → episodes (seriesId = the IPTV series id the player needs). */
    fun iptvEpisodeItems(json: String?): Pair<List<ChanItem>, Int> {
        val r = runCatching { JSONObject(json ?: "") }.getOrNull() ?: return emptyList<ChanItem>() to 0
        val list = r.optJSONArray("items")
        val seen = HashSet<String>()
        val items = ArrayList<ChanItem>()
        for (k in 0 until (list?.length() ?: 0)) {
            val o = list!!.opt(k) as? JSONObject ?: continue
            val id = o.opt("id") as? String ?: ""
            val seriesId = o.opt("seriesId") as? String ?: ""
            val seriesTitle = o.opt("seriesTitle") as? String ?: ""
            val season = (o.opt("season") as? Number)?.toDouble()?.takeIf { it.isFinite() }?.let { floor(it).toInt() } ?: 0
            val ep = (o.opt("episode") as? Number)?.toDouble()?.takeIf { it.isFinite() }?.let { floor(it).toInt() } ?: -1
            val secs = (o.opt("runtime") as? Number)?.toDouble()?.takeIf { it.isFinite() }?.let { floor(it).toLong() } ?: 0L
            if (!isIptvEpisodeId(id) || !VOD_ID_RE.matches(seriesId) || !seriesId.contains(":s:") || seriesTitle.isEmpty() ||
                season < 1 || ep < 0 || id in seen || o.opt("langUnknown") == true
            ) {
                continue
            }
            if (secs < IPTV_EP_MIN_S || secs > IPTV_EP_MAX_S) continue
            seen += id
            items +=
                ChanItem(
                    id = id,
                    name = (o.opt("title") as? String)?.takeIf { it.isNotEmpty() } ?: "Episode $ep",
                    type = "Episode",
                    seriesName = seriesTitle,
                    seriesId = seriesId,
                    season = season,
                    episode = ep,
                    year = (o.opt("year") as? Number)?.toInt(),
                    runTimeTicks = secs * TICKS_PER_SECOND,
                    seriesTmdb = (o.opt("tmdbId") as? Number)?.toLong()?.toString(),
                    art = art(o),
                    aff = serverAff(o),
                )
        }
        return items to pending(r)
    }

    private fun art(o: JSONObject): String? =
        (o.opt("backdrop") as? String)?.takeIf { TMDB_ART.containsMatchIn(it) }
            ?: (o.opt("poster") as? String)?.takeIf { TMDB_ART.containsMatchIn(it) }

    private fun serverAff(o: JSONObject): Double? = (o.opt("affinity") as? Number)?.toDouble()?.takeIf { it.isFinite() }?.coerceIn(0.0, 1.0)

    private fun pending(r: JSONObject): Int = (r.opt("pending") as? Number)?.toDouble()?.takeIf { it > 0 }?.let { floor(it).toInt() } ?: 0
}
